"""Phase 06 LLM-judge arbitration -- closes Phase 06 one way or the other.

Run: C:\\conda-envs\\drlca-rag\\python.exe scripts\\judge_phase06.py [--limit N] [--dry-run]
     (from D:\\NGORAG)

WHAT THIS SETTLES
-----------------
scripts/eval_phase06.py is a custom ZERO-LLM proxy for the RAGAS metrics. It is
deterministic and free, but its own docstring admits two blind spots: it cannot
see subtle misattribution, and its relevancy metric is a word-overlap FLOOR,
not aboutness. Phase 06 therefore ended with three items nobody had arbitrated:

  A. reverse_rel = 0.630, below the 0.80 gate. Is that a real relevancy
     failure, or an artifact of using reverse retrieval as a proxy?
  B. Q3 and Q8 answers look THIN. Thin-but-correct, or actually incomplete?
  C. The s.39 and s.34 citation dispositions -- the misattributions that used
     to need hand-written MANUAL_FLAGS entries.

An honest FAIL closes Phase 06 just as well as a PASS. The point is a verdict
with reasoning attached, not a better-looking number.

METHODOLOGY: GENERATOR != JUDGE
-------------------------------
Answers under review were generated by `gemini-2.5-flash` (rag.MODEL_NAME).
This script judges with `gemini-2.5-flash-lite` (resolved via
client.models.list() on 2026-09-11 -- a listing call, no generation quota).

Using a different model is a METHODOLOGICAL IMPROVEMENT, not merely a quota
dodge. A model grading its own output shares its own blind spots and tends to
ratify them; the split removes that specific failure mode. It does not remove
judge bias in general -- a Gemini model judging a Gemini model is still not
independent, and that limitation is recorded rather than papered over.

The judge is shown the question, the retrieved context and the answer. It is
NEVER shown the proxy's score for that item, so it cannot anchor on it. The
comparison proxy-vs-judge is done afterwards, in code.

QUOTA DISCIPLINE
----------------
Free tier is ~20 calls/day/model, and the two models have SEPARATE pools, so
this run cannot starve the generator. Tasks are priority-ordered: the 13 that
actually decide A/B/C run first, the 9 supplementary faithfulness checks last.

Every completed call is checkpointed to disk IMMEDIATELY, so a 429 halfway
through loses nothing and a re-run resumes where it stopped. A failed call
records `llm_error` and stays PENDING -- it is never backfilled with a guess.
That is the same rule the Phase 02 harness follows: never fake a row.
"""

